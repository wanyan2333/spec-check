"""Render a CheckReport as a Markdown "release evidence" document."""

from spec_check.models import CheckReport, CriterionResult

_LANGS = {
    ".py": "python",
    ".ts": "typescript",
    ".js": "javascript",
    ".go": "go",
    ".java": "java",
    ".rb": "ruby",
    ".rs": "rust",
}


def overall_verdict(report: CheckReport) -> str:
    gaps = sum(r.has_gap for r in report.results)
    review = sum(r.needs_human_review for r in report.results)
    if not gaps and not review:
        return "✅ READY — every criterion is implemented and tested, with verified evidence"
    parts = []
    if gaps:
        parts.append(f"❌ GAPS FOUND in {gaps} of {len(report.results)} criteria")
    if review:
        parts.append(f"⚠️ {review} criteria need human review")
    return " · ".join(parts)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _status(result: CriterionResult) -> str:
    if result.needs_human_review:
        return "⚠️ needs human review"
    return "✅ verified"


def _lang(path: str) -> str:
    for ext, lang in _LANGS.items():
        if path.endswith(ext):
            return lang
    return ""


def render_markdown(report: CheckReport) -> str:
    out: list[str] = []
    out.append(f"# Release evidence: {report.title}")
    out.append("")
    out.append(f"**Verdict:** {overall_verdict(report)}")
    out.append("")
    out.append(
        f"Model `{report.model}` · prompt `{report.prompt_version}` · "
        f"evidence snippets verified: {report.total_snippets - report.unverified_snippets}"
        f"/{report.total_snippets} (**{report.unverified_snippets} UNVERIFIED**)"
    )
    if report.user_story:
        out += ["", f"> {report.user_story}"]

    out += ["", "## Summary", ""]
    out.append("| ID | Acceptance criterion | Implemented | Tested | Confidence | Evidence check |")
    out.append("|----|----------------------|-------------|--------|------------|----------------|")
    for r in report.results:
        out.append(
            f"| {r.id} | {_cell(r.text)} | {r.implemented} | {r.tested} | "
            f"{r.confidence:.2f} | {_status(r)} |"
        )

    out += ["", "## Details"]
    for r in report.results:
        out += ["", f"### {r.id}: {r.text}", ""]
        out.append(
            f"- Implemented: **{r.implemented}** · Tested: **{r.tested}** · "
            f"Confidence: {r.confidence:.2f}"
        )
        out.append(f"- Reasoning: {r.reasoning}")
        if r.needs_human_review:
            out.append("- ⚠️ **Needs human review:** " + "; ".join(r.review_reasons))
        if not r.evidence:
            out.append("- Evidence: _none cited_")
        for e in r.evidence:
            if e.verified:
                label = "✅ verified"
            else:
                label = f"❌ **UNVERIFIED** ({e.note})"
            kind = "test" if e.is_test_file else "code"
            out += [
                "",
                f"`{e.file}` ({kind}) — {label}",
                "",
                f"```{_lang(e.file)}",
                e.snippet.rstrip("\n"),
                "```",
            ]

    out += ["", "## Model calls", ""]
    out.append("| # | Purpose | Latency (s) | Prompt tokens | Completion tokens | Retries |")
    out.append("|---|---------|-------------|---------------|-------------------|---------|")
    for i, c in enumerate(report.calls, 1):
        out.append(
            f"| {i} | {c.purpose} | {c.latency_s:.2f} | {c.prompt_tokens} | "
            f"{c.completion_tokens} | {c.retries} |"
        )
    out += [
        "",
        "_Generated by spec-check. LLM judgments are advisory: evidence marked "
        "UNVERIFIED could not be found in the diff and must be checked by a human._",
        "",
    ]
    return "\n".join(out)
